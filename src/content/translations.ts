const TRANSLATED_KEYS = new Set(["title", "subheading", "buttonLabel"]);

/** Deep copy of a content structure with every title/subheading/buttonLabel translated. */
export function localizeContent<T>(content: T, locale: Locale): T {
  if (locale === "de") return content;
  if (Array.isArray(content)) return content.map((item) => localizeContent(item, locale)) as T;
  if (content && typeof content === "object") {
    return Object.fromEntries(
      Object.entries(content).map(([key, value]) => [
        key,
        TRANSLATED_KEYS.has(key) && typeof value === "string"
          ? translateContent(value, locale)
          : localizeContent(value, locale),
      ]),
    ) as T;
  }
  return content;
}
